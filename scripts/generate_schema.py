#!/usr/bin/env python3
"""Generate schema/skill-frontmatter.schema.json from schema/allowed_values.py.

The JSON Schema (draft 2020-12) is the formal, tool-agnostic statement of the
SKILL.md frontmatter contract. It is GENERATED so the enum values, required
keys and limits exist in exactly one hand-edited place (allowed_values.py);
editing the JSON by hand is pointless because `--check` (run by the tests and
by validate_skills.py) fails until it matches the generator again.

Usage:
    python scripts/generate_schema.py           # print the schema to stdout
    python scripts/generate_schema.py --check   # exit 1 if the committed file is stale
    python scripts/generate_schema.py --write   # (re)write the committed file
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "schema"))

import allowed_values as av  # noqa: E402

SCHEMA_PATH = Path(__file__).resolve().parent.parent / "schema" / "skill-frontmatter.schema.json"


def build_schema() -> dict:
    slug = {"type": "string", "pattern": av.SLUG_PATTERN}
    props: dict[str, dict] = {}
    for key in av.STRING_KEYS:
        props[key] = {"type": "string", "minLength": 1}
    props["name"].update({"pattern": av.SLUG_PATTERN, "maxLength": av.NAME_MAX_LENGTH})
    props["description"]["maxLength"] = av.DESCRIPTION_MAX_LENGTH
    for key, values in av.ENUM_KEYS.items():
        props[key] = {"type": "string", "enum": list(values)}
    props[av.DATE_KEY] = {"type": "string", "pattern": av.DATE_PATTERN, "format": "date"}
    # `requires:` with no items is YAML null and means "none" -> allow null.
    for key in av.SLUG_LIST_KEYS:
        props[key] = {"type": ["array", "null"], "items": dict(slug), "uniqueItems": True}
    for key in av.TEXT_LIST_KEYS:
        props[key] = {"type": ["array", "null"], "items": {"type": "string", "minLength": 1}, "uniqueItems": True}

    order = list(av.REQUIRED_KEYS) + [k for k in av.OPTIONAL_KEYS if k not in av.REQUIRED_KEYS]
    missing = set(order) ^ set(props)
    if missing:
        raise SystemExit(f"allowed_values.py key lists are inconsistent (no type for / unlisted): {sorted(missing)}")
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "SKILL.md frontmatter",
        "description": ("GENERATED by scripts/generate_schema.py from schema/allowed_values.py; do not edit by "
                        "hand. Rules JSON Schema cannot express (future last_verified, reserved words in "
                        "name, XML tags in description, cross-skill references) are enforced by "
                        "scripts/validate_skills.py."),
        "type": "object",
        "required": list(av.REQUIRED_KEYS),
        "additionalProperties": False,
        "properties": {k: props[k] for k in order},
    }


def render() -> str:
    return json.dumps(build_schema(), indent=2, ensure_ascii=False) + "\n"


def check() -> list[str]:
    if not SCHEMA_PATH.exists():
        return [f"{SCHEMA_PATH.name} does not exist; run: python scripts/generate_schema.py --write"]
    if SCHEMA_PATH.read_text(encoding="utf-8") != render():
        return [f"{SCHEMA_PATH.name} is stale relative to schema/allowed_values.py; "
                "run: python scripts/generate_schema.py --write"]
    return []


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="exit 1 if the committed schema is stale")
    g.add_argument("--write", action="store_true", help="rewrite the committed schema")
    args = ap.parse_args()
    if args.check:
        problems = check()
        for p in problems:
            print(f"SCHEMA DRIFT: {p}")
        if not problems:
            print(f"{SCHEMA_PATH.name} is up to date")
        return 1 if problems else 0
    if args.write:
        SCHEMA_PATH.write_text(render(), encoding="utf-8", newline="\n")
        print(f"wrote {SCHEMA_PATH}")
        return 0
    sys.stdout.write(render())
    return 0


if __name__ == "__main__":
    sys.exit(main())
