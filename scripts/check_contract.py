#!/usr/bin/env python3
"""Guard the library's public contract against accidental breaking changes.

The *public contract* is everything a downstream user or tool can depend on
by name: the skill slugs, the plugin names and which skills each plugin
ships (from scripts/generate_plugins.build_plan), the marketplace name, the
frontmatter required/optional keys and every enum value
(schema/allowed_values.py), and the VERSION. It is locked in
schema/public-contract.json.

    python scripts/check_contract.py           # print the current contract and its diff vs the lock
    python scripts/check_contract.py --check   # exit 1 if the contract differs from the lock
    python scripts/check_contract.py --check --base-ref "$BASE_SHA"   # ...and vs the base commit's lock (CI)
    python scripts/check_contract.py --check --base-ref HEAD^1   # ...the same against the first parent (local)
    python scripts/check_contract.py --write   # re-lock, refusing unversioned BREAKING changes

Rules (see docs/SKILL-SPEC.md "Public contract lock"):
  * --check fails whenever the computed contract differs from the lock, so
    a contract change is always an explicit, reviewed `--write`.
  * --write refuses a BREAKING change (removed skill/plugin/plugin member/
    enum value/optional key, removed or demoted required key, new required
    key, renamed marketplace) unless VERSION's major is greater than the
    major recorded in the lock, and refuses a VERSION lower than the lock's.
  * --check --base-ref REF applies the same two rules against the lock as
    committed at REF (`git show REF:schema/public-contract.json`). The
    same-commit lock alone can be hand-edited to match a breaking tree, so
    CI compares against the base commit's lock too. If REF has no lock yet
    (the change that introduces it) that comparison is skipped and said so;
    a REF that does not resolve, or an unreadable base lock, is an error.
  * both require CHANGELOG.md to contain a `## [<VERSION>]` heading.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "schema"))

import allowed_values as av  # noqa: E402
import generate_plugins as gp  # noqa: E402
import skills_lib as sl  # noqa: E402

LOCK_PATH = sl.REPO_ROOT / "schema" / "public-contract.json"
LOCK_COMMENT = ("GENERATED by scripts/check_contract.py --write. Do not hand-edit; see docs/SKILL-SPEC.md "
                "'Public contract lock'.")
SEMVER_RE = re.compile(r"^(\d+)\.(\d+)\.(\d+)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$")


def parse_version(v: str) -> tuple[int, int, int]:
    m = SEMVER_RE.match(v.strip())
    if not m:
        raise ValueError(f"VERSION {v!r} is not MAJOR.MINOR.PATCH")
    return int(m.group(1)), int(m.group(2)), int(m.group(3))


def compute_contract(root: Path = sl.REPO_ROOT) -> dict:
    skills = sl.load_all_skills(root)
    plan = gp.build_plan(skills)
    return {
        "version": (root / "VERSION").read_text(encoding="utf-8").strip(),
        "marketplace": gp.MARKETPLACE_NAME,
        "skills": sorted(s.slug for s in skills),
        "plugins": {name: sorted(plan[name]["slugs"]) for name in sorted(plan)},
        "frontmatter": {
            "required": list(av.REQUIRED_KEYS),
            "optional": [k for k in av.OPTIONAL_KEYS if k not in av.REQUIRED_KEYS],
        },
        "enums": {k: list(v) for k, v in av.ENUM_KEYS.items()},
    }


def _strip(lock: dict) -> dict:
    return {k: v for k, v in lock.items() if not k.startswith("_")}


def diff_contract(old: dict, new: dict) -> tuple[list[str], list[str]]:
    """Return (breaking, non_breaking) human-readable change descriptions."""
    breaking: list[str] = []
    other: list[str] = []

    def setdiff(a, b):
        return sorted(set(a) - set(b)), sorted(set(b) - set(a))

    if old.get("version") != new.get("version"):
        other.append(f"VERSION {old.get('version')} -> {new.get('version')}")
    if old.get("marketplace") != new.get("marketplace"):
        breaking.append(f"marketplace renamed {old.get('marketplace')!r} -> {new.get('marketplace')!r}")

    removed, added = setdiff(old.get("skills", []), new.get("skills", []))
    breaking += [f"skill removed: {s}" for s in removed]
    other += [f"skill added: {s}" for s in added]

    old_p, new_p = old.get("plugins", {}), new.get("plugins", {})
    removed, added = setdiff(old_p, new_p)
    breaking += [f"plugin removed: {p}" for p in removed]
    other += [f"plugin added: {p}" for p in added]
    for p in sorted(set(old_p) & set(new_p)):
        gone, new_members = setdiff(old_p[p], new_p[p])
        breaking += [f"skill {s} removed from plugin {p}" for s in gone]
        other += [f"skill {s} added to plugin {p}" for s in new_members]

    old_fm, new_fm = old.get("frontmatter", {}), new.get("frontmatter", {})
    old_req, new_req = set(old_fm.get("required", [])), set(new_fm.get("required", []))
    old_opt, new_opt = set(old_fm.get("optional", [])), set(new_fm.get("optional", []))
    for k in sorted(new_req - old_req):
        breaking.append(f"new required frontmatter key: {k} (every existing skill must now declare it)")
    for k in sorted(old_req - new_req):
        where = "demoted to optional" if k in new_opt else "removed"
        breaking.append(f"required frontmatter key {where}: {k} (consumers may rely on its presence)")
    for k in sorted(old_opt - new_opt - new_req):
        breaking.append(f"optional frontmatter key removed: {k}")
    for k in sorted(new_opt - old_opt - old_req):
        other.append(f"optional frontmatter key added: {k}")

    old_e, new_e = old.get("enums", {}), new.get("enums", {})
    for k in sorted(set(old_e) - set(new_e)):
        breaking.append(f"enum removed: {k}")
    for k in sorted(set(new_e) - set(old_e)):
        other.append(f"enum added: {k}")
    for k in sorted(set(old_e) & set(new_e)):
        gone, new_vals = setdiff(old_e[k], new_e[k])
        breaking += [f"enum value removed: {k}={v}" for v in gone]
        other += [f"enum value added: {k}={v}" for v in new_vals]
    return breaking, other


def changelog_problem(root: Path, version: str) -> str | None:
    path = root / "CHANGELOG.md"
    if not path.exists():
        return "CHANGELOG.md does not exist"
    if not re.search(rf"^## \[{re.escape(version)}\]", path.read_text(encoding="utf-8"), flags=re.MULTILINE):
        return (f"CHANGELOG.md has no '## [{version}]' heading for the current VERSION; add a section "
                "describing this release")
    return None


def check(current: dict, lock: dict | None, root: Path) -> list[str]:
    problems: list[str] = []
    if lock is None:
        problems.append("no contract lock found; run: python scripts/check_contract.py --write")
    elif _strip(lock) != current:
        breaking, other = diff_contract(_strip(lock), current)
        lines = [f"  BREAKING: {c}" for c in breaking] + [f"  change:   {c}" for c in other]
        hint = ("bump VERSION's major, add a CHANGELOG.md section for it, then run: "
                "python scripts/check_contract.py --write") if breaking else (
            "run: python scripts/check_contract.py --write (and describe the change in CHANGELOG.md)")
        problems.append("public contract changed without regenerating schema/public-contract.json:\n"
                        + "\n".join(lines or ["  (formatting/order only)"]) + f"\n  -> {hint}")
    cl = changelog_problem(root, current["version"])
    if cl:
        problems.append(cl)
    return problems


def versioning_problems(current: dict, old: dict, against: str = "the locked",
                        refusal: str = "refusing to lock") -> list[str]:
    """The VERSION rules relative to an older lock: never lower, and a major bump for BREAKING."""
    try:
        new_v = parse_version(current["version"])
    except ValueError as e:
        return [str(e)]
    try:
        old_v = parse_version(old.get("version", "0.0.0"))
    except ValueError:
        old_v = (0, 0, 0)
    problems: list[str] = []
    if new_v < old_v:
        problems.append(f"VERSION {current['version']} is lower than {against} {old.get('version')}")
    breaking, _ = diff_contract(old, current)
    if breaking and new_v[0] <= old_v[0]:
        problems.append(
            f"{refusal} BREAKING change(s) without a major version bump ({against} "
            f"{old.get('version')}, VERSION {current['version']}):\n"
            + "\n".join(f"  BREAKING: {c}" for c in breaking)
            + f"\n  -> set VERSION to {old_v[0] + 1}.0.0 (and add its CHANGELOG.md section), or revert the change")
    return problems


def write_problems(current: dict, lock: dict | None, root: Path) -> list[str]:
    try:
        parse_version(current["version"])
    except ValueError as e:
        return [str(e)]
    problems = versioning_problems(current, _strip(lock)) if lock is not None else []
    cl = changelog_problem(root, current["version"])
    if cl:
        problems.append(cl)
    return problems


def load_lock(path: Path) -> dict | None:
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def load_base_lock(root: Path, ref: str, lock_path: Path) -> tuple[dict | None, str | None]:
    """(lock committed at `ref`, error). (None, None) means `ref` has no lock file."""
    try:
        rel = lock_path.resolve().relative_to(root).as_posix()
    except ValueError:
        return None, f"--base-ref needs the lock inside --root ({lock_path} is not under {root})"

    def git(*args: str) -> subprocess.CompletedProcess:
        return subprocess.run(["git", "-C", str(root), *args], capture_output=True)

    try:
        if git("rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}").returncode != 0:
            return None, f"base ref {ref!r} does not resolve to a commit (fetch it, e.g. actions/checkout fetch-depth: 0)"
        if git("cat-file", "-e", f"{ref}:./{rel}").returncode != 0:
            return None, None
        shown = git("show", f"{ref}:./{rel}")
    except OSError as e:
        return None, f"cannot run git for --base-ref: {e}"
    if shown.returncode != 0:
        return None, f"git show {ref}:./{rel} failed: {shown.stderr.decode('utf-8', 'replace').strip()}"
    try:
        lock = json.loads(shown.stdout.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as e:
        return None, f"the lock at {ref} is not valid JSON: {e}"
    if not isinstance(lock, dict):
        return None, f"the lock at {ref} is not a JSON object"
    return lock, None


def render_lock(current: dict) -> str:
    return json.dumps({"_comment": LOCK_COMMENT, **current}, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="exit 1 if the contract differs from the lock")
    g.add_argument("--write", action="store_true", help="re-lock the current contract")
    ap.add_argument("--root", type=Path, default=sl.REPO_ROOT, help="repo root (VERSION, CHANGELOG.md, skills)")
    ap.add_argument("--lock", type=Path, default=None, help="lock file (default: <root>/schema/public-contract.json)")
    ap.add_argument("--base-ref", default=None, metavar="REF",
                    help="with --check: also apply the VERSION rules against the lock committed at this git ref")
    args = ap.parse_args(argv)
    if args.base_ref and not args.check:
        ap.error("--base-ref requires --check")

    root = args.root.resolve()
    lock_path = args.lock or root / "schema" / "public-contract.json"
    current = compute_contract(root)
    lock = load_lock(lock_path)

    if args.check:
        problems = check(current, lock, root)
        base_note = ""
        if args.base_ref:
            base, err = load_base_lock(root, args.base_ref, lock_path)
            if err:
                problems.append(err)
            elif base is None:
                base_note = f"; {args.base_ref} has no {lock_path.name}, base-lock comparison skipped"
            else:
                base_problems = versioning_problems(current, _strip(base), against=f"the lock at {args.base_ref}",
                                                    refusal="this change makes")
                problems += base_problems
                # Only claim the rules hold when they do; a failure is already explained above.
                verdict = "violated" if base_problems else "hold"
                base_note = f"; VERSION rules {verdict} vs the lock at {args.base_ref} (version {base.get('version')})"
        for p in problems:
            print(f"CONTRACT ERROR: {p}")
        if not problems:
            print(f"public contract matches {lock_path.name} (version {current['version']}, "
                  f"{len(current['skills'])} skills, {len(current['plugins'])} plugins){base_note}")
        elif base_note:
            print(f"note: {base_note[2:]}")
        return 1 if problems else 0

    if args.write:
        problems = write_problems(current, lock, root)
        for p in problems:
            print(f"CONTRACT ERROR: {p}")
        if problems:
            return 1
        lock_path.parent.mkdir(parents=True, exist_ok=True)
        lock_path.write_text(render_lock(current), encoding="utf-8", newline="\n")
        print(f"wrote {lock_path}")
        return 0

    print(json.dumps(current, indent=2))
    if lock is not None:
        breaking, other = diff_contract(_strip(lock), current)
        for c in breaking:
            print(f"BREAKING vs lock: {c}")
        for c in other:
            print(f"change vs lock: {c}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
